using Mutagen.Bethesda;
using Mutagen.Bethesda.Synthesis;
using Mutagen.Bethesda.Skyrim;
using Mutagen.Bethesda.Plugins;
using Mutagen.Bethesda.Plugins.Records;

namespace EquipmentBalancePatcher;

public static class Program
{
    private static Lazy<Settings> _settings = null!;
    public static PatcherPreferences AuditPreferences() => new() { NoPatch = true };

    public static async Task<int> Main(string[] args)
    {
        var result = await SynthesisPipeline.Instance
            .AddPatch<ISkyrimMod, ISkyrimModGetter>(RunPatch, AuditPreferences())
            .SetAutogeneratedSettings("Settings", "settings.json", out _settings)
            .SetTypicalOpen(GameRelease.SkyrimSE, "EBP.esp")
            .Run(args).ConfigureAwait(false);
        // Settings/version queries have machine-readable stdout; never append lifecycle text there.
        if (args.Length == 0 || args[0] == "run-patcher")
            Console.WriteLine($"[EBP lifecycle] Synthesis pipeline returned; exit code {result}.");
        return result;
    }

    public static void RunPatch(IPatcherState<ISkyrimMod, ISkyrimModGetter> state)
        => RunAudit(state, _settings.Value);

    public static void RunAudit(IPatcherState<ISkyrimMod, ISkyrimModGetter> state, Settings settings)
    {
        Console.WriteLine("[EBP lifecycle] Audit started (NoPatch=true; stored fields only).");
        var output = ReportWriter.ResolveDirectory(settings.OutputDirectory, state.ExtraSettingsDataPath);
        ReportWriter.ValidateDirectory(output);
        var reader = new EquipmentReader(state.LinkCache);
        var snapshots = reader.Read(
            state.LoadOrder.PriorityOrder.Weapon().WinningContextOverrides(includeDeletedRecords: true)
                .Select(context => (context.Record, context.ModKey)),
            state.LoadOrder.PriorityOrder.Armor().WinningContextOverrides(includeDeletedRecords: true)
                .Select(context => (context.Record, context.ModKey)), state.Cancel);
        var inputs = state.LoadOrder.ListedOrder.Select(listing =>
            new InputPlugin(listing.ModKey.ToString(), listing.Enabled)).ToArray();
        // The inventory already contains all winning equipment parents. Probe only absent keys to
        // distinguish a link to another record type from a missing/unresolved link, without changing raw data.
        string? MissingTemplateTargetStatus(string key) => state.LinkCache.TryResolve<IMajorRecordGetter>(FormKey.Factory(key), out var target)
            ? target.IsDeleted ? "DeletedParent" : "WrongTypeParent" : null;
        var report = InventoryAudit.Build(snapshots, inputs, settings, state.Cancel, MissingTemplateTargetStatus);
        var paths = ReportWriter.Write(report, output, state.Cancel);
        Console.WriteLine(ReportWriter.ConsoleSummary(report, paths));
        Console.WriteLine("[EBP lifecycle] Reports published; audit callback returning normally.");
    }
}
